  test "every captured genre and category has the reviewed mapping" do
    assert Enum.count(@production_cases, &(elem(&1, 0) == "genres")) == 326
    assert Enum.count(@production_cases, &(elem(&1, 0) == "categories")) == 883

    for {source, name, expected} <- @production_cases do
      actual = Normalizer.normalize(name)

      assert actual == expected,
             "#{source}: #{inspect(name)}: #{inspect(actual)} != #{inspect(expected)}"

      assert Enum.all?(actual, &Vocabulary.slug?/1)
    end
  end

  test "folding, decoration, separators and whole phrase precedence" do
    cases = [
      {nil, []},
      {"", []},
      {"  ", []},
      {"  ⭐ • - FILME |  AÇÃO  ", ~w(acao)},
      {"SÉRIES:   Ficção   Científica", ~w(ficcao-cientifica)},
      {"canais | jornalismo", ~w(noticias)},
      {"Comédia Romântica / talk show / Reality Show", ~w(comedia romance talk-show reality)},
      {"crime, drama; mystery + horror • romance | music and history e war & politics",
       ~w(crime drama misterio terror romance musica historia guerra politica)},
      {"artes e cultura / cinema tv / mini-dramas / dramas curtos / drama", ~w(drama)},
      {"drama / drama / Drama & Romance", ~w(drama romance)},
      {"estranho drama / dramatico / dramas curtos / adrama / drama desconhecido", []},
      {"realityshow / talkative / Rio / entretenimento / Rocance", []},
      {"unknown | drama", ~w(drama)},
      {"sci-fi & fantasy / comédia romântica", ~w(ficcao-cientifica fantasia comedia romance)}
    ]

    for {name, expected} <- cases do
      assert Normalizer.normalize(name) == expected, inspect(name)
    end
  end

  test "adult markers and reels reject the entire string before decoration or splitting" do
    for marker <-
          ~w(adulto adultos xxx XXXX +18 18+ hentai onlyfans privacy brasileirinhas erotico eróticos erótica eróticas),
        name <- ["Drama / #{marker}", "#{marker} | Comédia", "▶️ FILMES | Ação + #{marker}"] do
      assert Normalizer.normalize(name) == [], inspect(name)
    end

    for name <- ["[Reels] Drama", "▶️ [REELS] Animação", "Séries | [Reels] Comédia"] do
      assert Normalizer.normalize(name) == []
    end

    assert Normalizer.normalize("Drama / adulthood / xxxtra / privacyless") == ["drama"]
  end

